#include <iostream>
using namespace std;

int main()
{
    // Type Casting : Implicit Type Casting 

    // int to float 

    int num1 = 10;
    float num2 = 5.6;
    int result = num1 + num2;

    cout << result <<endl;
    cout << num1 + num2 <<endl;

    // char to int conversion 

    char ch = 'A';
    int a = ch + 1;
    cout << a <<endl;

    // int to char conversion

    int x = 64;
    char alphabet = x + 1;

    cout << alphabet <<endl;



    
    
    return 0;
    
}