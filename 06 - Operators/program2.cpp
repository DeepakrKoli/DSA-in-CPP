#include <iostream>
using namespace std;

int main()
{
    
    // Binary Operator 

    // Arithmetic Operator 

    int a = 10;
    int b = 5;

    cout << ( a + b ) <<endl; // 15
    cout << ( a - b ) <<endl; // 5
    cout << ( a * b ) <<endl; // 50
    cout << ( a / b ) <<endl; // 2
    cout << ( a % b ) <<endl; // 0

    // Typecasting 
    cout << ( 5 / 3) << endl; // 1
    cout << ( 5.0 / 3) << endl; // 1.666666

    
    
    return 0;
    
}