#include <iostream>
using namespace std;

int main()
{
    
    // Relational Operator

    cout << ( 10 == 5 ) <<endl; // 0
    cout << ( 10 > 5 ) <<endl; // 1
    cout << (10 < 5) <<endl; // 0
    cout << (10 >= 5)<<endl; // 1
    cout << (10 <= 5)<<endl; // 0
    cout << (10 != 5)<<endl; // 1
    cout << (10 != 10) <<endl; // 0

    
    
    return 0;
    
}