// check if number is greater than 100 or not

#include <iostream>
using namespace std;

int main()
{
    
    int num;
    cout << "Enter number :";
    cin >> num;

    if( num > 100){
        cout << "Entered number is greater than 100";
    }
    else {
        cout << "Entered number is not greater than 100";
    }
    
    
    return 0;
    
}